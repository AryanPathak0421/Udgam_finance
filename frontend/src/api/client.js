// Default: empty, so calls go to /api on the same origin (Vite proxy in dev, the
// vercel.json rewrite in production) and the auth cookie stays first-party.
// Only set VITE_API_BASE_URL to call an API on another domain directly.
const API_BASE = (import.meta.env.VITE_API_BASE_URL || '').replace(/\/$/, '');

async function request(path, { method = 'GET', body } = {}) {
  const res = await fetch(`${API_BASE}/api${path}`, {
    method,
    credentials: 'include',
    headers: body !== undefined ? { 'Content-Type': 'application/json' } : undefined,
    body: body !== undefined ? JSON.stringify(body) : undefined,
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) {
    // An expired session on a protected call sends the user back to login.
    if (res.status === 401 && !path.startsWith('/auth/')) window.dispatchEvent(new Event('auth:expired'));
    const err = new Error(data.message || 'Something went wrong');
    err.status = res.status;
    err.errors = data.errors || {};
    throw err;
  }
  return data;
}

const qs = (params = {}) => {
  const p = new URLSearchParams();
  Object.entries(params).forEach(([k, v]) => v !== '' && v != null && p.set(k, v));
  const s = p.toString();
  return s ? `?${s}` : '';
};

// A heavy report answers "pending" while the server works it out; ask again until it is there (about 10 minutes at most).
async function slow(path, params) {
  let data = await request(`${path}${qs(params)}`);
  for (let i = 0; data?.pending && i < 200; i += 1) {
    // eslint-disable-next-line no-await-in-loop
    await new Promise((r) => { setTimeout(r, 3000); });
    // eslint-disable-next-line no-await-in-loop
    data = await request(`${path}${qs({ ...params, poll: 1 })}`);
  }
  if (data?.pending) throw new Error('The report is taking too long. Try a smaller period or one branch.');
  return data;
}

