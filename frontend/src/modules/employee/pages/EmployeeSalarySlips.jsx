import { useEffect, useState } from 'react';
import { api } from '../../../api/client.js';
import { useEmployeeApp } from '../EmployeeAppContext.jsx';

export default function EmployeeSalarySlips() {
  const { t } = useEmployeeApp();
  const [slips, setSlips] = useState([]);
  const [loading, setLoading] = useState(true);
  const [activeSlip, setActiveSlip] = useState(null);

  useEffect(() => {
    api.employeeApp.salarySlips()
      .then((res) => {
        setSlips(res.items || []);
        if (res.items && res.items.length > 0) {
          setActiveSlip(res.items[0]);
        }
      })
      .catch((err) => console.error(err))
      .finally(() => setLoading(false));
  }, []);

  return (
    <div className="emp-page-container">
      <div className="emp-card">
        <h2 style={{ fontSize: '1.2rem', fontWeight: 800, margin: '0 0 6px 0', color: 'var(--emp-text)' }}>
          💵 Month-Wise Salary Slips
        </h2>
        <p style={{ fontSize: '0.8rem', color: 'var(--emp-text-muted)', margin: 0 }}>
          View and download your monthly salary statements and deduction details.
        </p>
      </div>

      {loading ? (
        <div style={{ textAlign: 'center', padding: '30px', color: 'var(--emp-text-muted)' }}>Loading salary slips...</div>
      ) : slips.length === 0 ? (
        <div className="emp-card" style={{ textAlign: 'center', padding: '36px', color: 'var(--emp-text-muted)' }}>
          <div style={{ fontSize: '2.5rem', marginBottom: 8 }}>📄</div>
          <div style={{ fontWeight: 600 }}>No salary slips generated yet</div>
          <div style={{ fontSize: '0.8rem', marginTop: 4 }}>Salary slips will show here once generated by HR.</div>
        </div>
      ) : (
        <>
          {/* Active Slip Details Card */}
          {activeSlip && (
            <div className="emp-card" style={{ border: '2px solid var(--emp-primary)' }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', borderBottom: '1px solid var(--emp-border)', paddingBottom: 10, marginBottom: 12 }}>
                <div>
                  <div style={{ fontSize: '0.75rem', color: 'var(--emp-text-muted)' }}>SALARY SLIP FOR</div>
                  <h3 style={{ fontSize: '1.2rem', fontWeight: 800, margin: '2px 0 0 0', color: 'var(--emp-primary)' }}>
                    {activeSlip.month}
                  </h3>
                  <div style={{ fontSize: '0.78rem', color: 'var(--emp-text-muted)', marginTop: 2 }}>
                    {activeSlip.designation || 'Staff'} • {activeSlip.branch || 'Udgam'}
                  </div>
                </div>

                <div style={{ textAlign: 'right' }}>
                  <span className="emp-badge emp-badge-success" style={{ textTransform: 'uppercase' }}>
                    {activeSlip.status || 'Paid'}
                  </span>
                  <div style={{ fontSize: '0.72rem', color: 'var(--emp-text-muted)', marginTop: 4 }}>
                    {activeSlip.paidDays} Paid Days
                  </div>
                </div>
              </div>

              {/* Net Pay Highlight Banner */}
              <div style={{ background: 'linear-gradient(135deg, #059669, #10b981)', color: '#fff', padding: '14px', borderRadius: 10, textAlign: 'center', marginBottom: 14 }}>
                <div style={{ fontSize: '0.75rem', opacity: 0.9, textTransform: 'uppercase' }}>Net Take-Home Salary</div>
                <div style={{ fontSize: '1.8rem', fontWeight: 800, marginTop: 2 }}>
                  ₹{Number(activeSlip.netSalary).toLocaleString('en-IN')}
                </div>
              </div>

              {/* Earnings & Deductions Breakdown */}
              <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 12, fontSize: '0.82rem' }}>
                <div style={{ background: 'var(--emp-card-bg)', border: '1px solid var(--emp-border)', padding: 10, borderRadius: 8 }}>
                  <div style={{ fontWeight: 700, color: '#059669', marginBottom: 6 }}>Earnings</div>
                  <div style={{ display: 'flex', justifyContent: 'space-between', padding: '3px 0' }}>
                    <span>Basic Pay:</span>
                    <strong>₹{Number(activeSlip.basicSalary).toLocaleString('en-IN')}</strong>
                  </div>
                  <div style={{ display: 'flex', justifyContent: 'space-between', padding: '3px 0' }}>
                    <span>Allowances:</span>
                    <strong>₹{Number(activeSlip.allowances).toLocaleString('en-IN')}</strong>
                  </div>
                </div>

                <div style={{ background: 'var(--emp-card-bg)', border: '1px solid var(--emp-border)', padding: 10, borderRadius: 8 }}>
                  <div style={{ fontWeight: 700, color: '#dc2626', marginBottom: 6 }}>Deductions</div>
                  <div style={{ display: 'flex', justifyContent: 'space-between', padding: '3px 0' }}>
                    <span>PF / ESI / Taxes:</span>
                    <strong>₹{Number(activeSlip.deductions).toLocaleString('en-IN')}</strong>
                  </div>
                </div>
              </div>
            </div>
          )}

          {/* List of Other Months */}
          <h4 style={{ fontSize: '0.95rem', fontWeight: 700, margin: '14px 0 8px 0' }}>All Monthly Statements</h4>
          <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
            {slips.map((s) => (
              <div
                key={s.id || s.month}
                onClick={() => setActiveSlip(s)}
                className="emp-card"
                style={{
                  margin: 0,
                  padding: 12,
                  cursor: 'pointer',
                  border: activeSlip?.month === s.month ? '2px solid var(--emp-primary)' : '1px solid var(--emp-border)',
                }}
              >
                <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                  <div>
                    <div style={{ fontWeight: 800, fontSize: '0.92rem' }}>{s.month}</div>
                    <div style={{ fontSize: '0.72rem', color: 'var(--emp-text-muted)' }}>Status: {s.status || 'Paid'}</div>
                  </div>
                  <div style={{ textAlign: 'right' }}>
                    <div style={{ fontWeight: 800, color: '#059669' }}>₹{Number(s.netSalary).toLocaleString('en-IN')}</div>
                    <span style={{ fontSize: '0.72rem', color: 'var(--emp-primary)' }}>View Slip →</span>
                  </div>
                </div>
              </div>
            ))}
          </div>
        </>
      )}
    </div>
  );
}

